# 형식: 오늘 하는 것·채용 연결 → 단계(시간 · 어디서) → 붙여 넣을 요청문 → 확인 표 → 기록
# 요청문은 한 줄, “ ”로 감싼다 (용어 주석이 붙지 않게)

def H(what, hire):
    return f'오늘 하는 것: {what}\n채용 연결: {hire}'

def S(n, title, mins, where, *lines):
    return f'{n}단계 {title} ({mins}분 · {where})\n' + '\n'.join(lines)

def P(text):
    return '그대로 붙여 넣을 요청문:\n“' + text + '”'

def T(head, *rows):
    out = ['| ' + ' | '.join(head) + ' |']
    out += ['| ' + ' | '.join(r) + ' |' for r in rows]
    return '\n'.join(out)

def REC(task, wrong, judge, cnt='3번 · 1번 · 45분'):
    return ('기록 (5분 · 앱의 결과물 기입표 · 요청 횟수와 시간은 ‘확인·수정 기록’ 칸)\n'
            + T(['적을 것', '예'],
                ['AI에 맡긴 일', task],
                ['AI가 틀리거나 지나친 것', wrong],
                ['내가 내린 판단 · 근거', judge])
            + '\n· 이 기록이 쌓여 사례의 ‘AI를 어떻게 썼나’ 단락과 면접 답이 된다')

PRIV = '· 올리기 전에: 실제 이름·전화번호·학생 정보는 지우거나 P1 · 학생A로 바꾼다'
OPEN = '· 받은 코드: 메모장에 붙여 넣기 → 파일 이름 끝을 .html로 저장 → 더블클릭하면 크롬으로 열린다'
ONE = '· 한 번에 하나만 고치게 한다 → 여러 개를 한꺼번에 고치면 무엇이 무엇을 고쳤는지, 무엇이 새로 망가졌는지 알 수 없다'

