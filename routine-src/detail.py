def clean_guide(b):
    for k, v in GUIDE_MAP:
        if b.guide and b.guide.startswith(k):
            b.guide = v; return

WORD = [('갱신한다', '고친다'), ('갱신된', '고친'), ('갱신', '수정'), ('대조', '비교'), ('비교가 성립한다', '비교할 수 있다'), ('성립한다', '맞는 말이 된다')]
def words(x):
    for a, b in WORD: x = x.replace(a, b)
    return x

