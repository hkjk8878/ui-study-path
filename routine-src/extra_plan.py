                b.steps = tuple(f(s) for s in b.steps)
                b.out, b.chk, b.note = f(b.out), f(b.chk), f(b.note or '')
                if had and b.t[:5] in ('08:00', '09:00') and any('동의 받기' in s for s in b.steps):
                    b.steps = (b.steps[0], MEMO_NOTE) + tuple(b.steps[1:])

