def apply(weeks):
    used=set()
    for w in weeks:
        for d in w.days:
            for b in d.blocks:
                k=(d.date[5:], b.t[:5])
                if k in NEWFIG:
                    assert not b.fig, k; b.fig=NEWFIG[k]; used.add(k)
                elif k in REF: b.guide='그림 참고: '+REF[k]; used.add(k)
                elif k in SELF: b.guide=SELF[k]; used.add(k)
                elif k in WATCH: b.guide=WATCH[k]
                elif b.kind=='훈련' and not b.fig: b.guide=SELF_TRAIN
                elif k==('11-10','22:00'): b.guide=AI_1110
                elif not b.fig and b.kind=='AI':
                    b.guide = AI_HTML if any('HTML' in x for x in (b.steps or [])) or 'HTML' in (b.out or '') else AI_TEXT
                elif not b.fig and b.kind=='강의' and b.res and not any('영상' in R[r][2].replace('영상 없음','') for r in b.res if r in R):
                    b.guide=LECT_DOC
                elif not b.fig and b.kind in DEFAULT: b.guide=DEFAULT[b.kind]
    miss=(set(NEWFIG)|set(REF)|set(SELF))-used
    assert not miss, miss
