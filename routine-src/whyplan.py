# 제목으로 정하는 반복 블록(위에 따로 적은 것이 우선)
TITLE = [('주간 기록', WEEKLY), ('파일럿', PILOT), ('대표 사례 보완', BOOST)]


def apply(weeks):
    used = set(); n = 0
    for w in weeks:
        for d in w.days:
            for b in d.blocks:
                key = (d.date[5:], b.t[:5])
                if key in WHY:
                    used.add(key)
                    if WHY[key]: b.why = WHY[key]; n += 1
                    continue
                for pat, txt in TITLE:
                    if pat in b.title:
                        b.why = txt; n += 1; break
    missing = set(WHY) - used
    assert not missing, sorted(missing)
    return n
